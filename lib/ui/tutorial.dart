import '../sim/world.dart';

/// Обучение для режима «С нуля»: задания по порядку.
class TutStep {
  final String title;
  final String hint;
  final bool Function(World w) done;
  const TutStep(this.title, this.hint, this.done);
}

bool _hasBuilt(World w, bool Function(String kind, String id) f) =>
    w.nodes.values.any((n) => !n.existing && n.def != null && f(n.def!.kind, n.def!.id));

final tutorialSteps = <TutStep>[
  TutStep(
    'Построй электростанцию',
    'Станции → «ТЭС (газ)»: ей не нужно топливо. Поставь её недалеко от крупного города. '
        'Внизу карточки видно, на каких напряжениях она работает (330/220/110 кВ).',
    (w) => _hasBuilt(w, (k, _) => k == 'plant' || k == 'storage'),
  ),
  TutStep(
    'Построй подстанцию ПС 330/110',
    'Сеть → «ПС 330/110». Ставь рядом с городом. Подстанция переводит магистральные 330 кВ '
        'в 110 кВ, на которых работают города.',
    (w) => _hasBuilt(w, (k, _) => k == 'sub'),
  ),
  TutStep(
    'Соедини станцию с подстанцией',
    'Сеть → «ЛЭП 330 кВ». Тапни станцию, потом подстанцию. Объекты, к которым можно подключиться, '
        'подсвечиваются цветом линии.',
    (w) => w.lines.values.any((l) =>
        !l.virtual && !l.existing && [l.a, l.b].any((id) => w.nodes[id]?.def?.isGenerator ?? false)),
  ),
  TutStep(
    'Дай свет городу',
    'Сеть → «ЛЭП 110 кВ»: от подстанции к городу. Когда город станет бирюзовым — он обеспечен на 100%.',
    (w) => w.nodes.values.any((n) => n.isCity && n.suppliedMw > 0 && n.supplyFrac > 0.99),
  ),
  TutStep(
    'Построй угольную шахту',
    'Добыча → «Угольная шахта». Серые круги — угольные бассейны (Донбасс, Львовско-Волынский). '
        'Шахте нужен свет: она сама подключится к городу или подстанции в радиусе 30 км.',
    (w) => _hasBuilt(w, (_, id) => id == 'coal_mine'),
  ),
  TutStep(
    'Построй ТЭС на угле',
    'Станции → «ТЭС (уголь)». Лучше недалеко от шахты — так быстрее возить. Подключи её ЛЭП к сети.',
    (w) => _hasBuilt(w, (_, id) => id == 'tes_coal'),
  ),
  TutStep(
    'Отправь грузовик с углём',
    'Транспорт → «Грузовик». Тапни шахту, потом ТЭС. Колонна поедет по реальным дорогам '
        'и будет возить уголь туда-обратно.',
    (w) => w.trucks.isNotEmpty || w.trains.isNotEmpty,
  ),
  TutStep(
    'Запусти ТЭС на угле',
    'Дождись, пока привезут уголь (ускорь время ▶▶▶). ТЭС начнёт выдавать ток, если она подключена к сети.',
    (w) => w.nodes.values.any((n) => !n.existing && n.def?.id == 'tes_coal' && n.genMw > 1),
  ),
  TutStep(
    'Выплавь 1000 т стали',
    'Добыча → «Рудник» в Кривбассе (красные круги) + Заводы → «Меткомбинат». '
        'Привези на комбинат руду и уголь двумя грузовиками.',
    (w) => (w.produced['steel'] ?? 0) >= 1000,
  ),
];
